def predict_cell_type_with_basin(path_in: Union[str, Path],
                                 path_out: Union[str, Path],
                                 # model_path: Union[str, Path],
                                 # model_name: str = "",
                                 model: OneModel = None,
                                 # mlflow: bool = False,
                                 device: str = 'cuda',
                                 num_workers: int = 8,
                                 batch_size: int = 2000,
                                 mean=None,
                                 std=None,
                                 brightness_factor=None
                                 ):
    """Store cell predictions on dataset in external file using basins

    This function assumes that `image_bg` was computed for the datasets
    beforehand.

    Parameter
    ---------
    path_in:
        Path of RTDC file for which cell prediction will be computed. This
        function requires "image_bg" to be computed beforehand (e.g. via
        dcevent)
    path_out:
        Save path of RTDC file only containing cell predictions. It will
        use the file in `path_in` as basin.
    model: model to be used for prediction
    device: {'cuda', 'cpu'}, optional
    num_workers: int, optional
        Count of threads used for Dataloader to load batches
    batch_size
        Batch size used for model inference.

    Note:
        This prediction-function creates basins and will not reference
        potientially existing `ml_score`-features in these basins. It will only
        contain its own predicten `ml_score`-features and therefore it is not
        necessary to clean up previous predictions.

    Raises:
        FileExistsError
            Raises error if `path_out` already exists
    """
    path_in = Path(path_in)
    path_out = Path(path_out)

    if path_out.exists():
        raise FileExistsError(f"File already exists at Path: '{path_out}'!")

    # logger.info(f"Cell Prediction of {path_in} -- Start Time: {time.ctime()}")
    # logger.info(f"Number of Workers: {num_workers}")
    # logger.info(f"Batch size: {batch_size}")

    # model = OneModel(model_path=model_path, device=device, model_name=model_name, mlflow=mlflow)

    logger.info(f"Cell Prediction in {path_in} -- Start Time: {time.ctime()}")
    prediction_probs = get_predictions(ds_path=path_in,
                                       model=model,
                                       batch_size=batch_size,
                                       num_workers=num_workers,
                                       device=device,
                                       mean=mean,
                                       std=std,
                                       brightness_factor=brightness_factor)

    logger.info(f"Cell Prediction -- End Time: {time.ctime()}")

    # prediction_probs_old = get_predictions_old(ds_path=path_in,
    #                                    model=model,
    #                                    batch_size=batch_size,
    #                                    num_workers=num_workers,
    #                                    device=device)

    # Write prediction to dataset
    logger.info("Writing Predictions to RTDC-Dataset...")
    with dclab.RTDCWriter(path_out, mode="reset") as writer, \
            dclab.new_dataset(path_in) as ds_in:

        # Write predictions to new dataset
        for idx, feat in enumerate(model.feature_names):
            writer.store_feature(feat, prediction_probs[:, idx])

        # Write Metadata to new dataset
        meta = dict(ds_in.config)
        meta.pop("filtering")
        writer.store_metadata(meta)

        basin_feats = [el for el in ds_in.features if "ml_" not in el]
        writer.store_basin(basin_name="segmentation_and_features",
                           basin_type="file",
                           basin_format="hdf5",
                           basin_locs=[path_in.resolve()],
                           basin_feats=basin_feats)

    # logger.info(f"Cell Prediction of {path_in} -- End Time: {time.ctime()}")


