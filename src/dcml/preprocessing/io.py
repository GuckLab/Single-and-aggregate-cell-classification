def remove_unlabeled_events(src: [str, Path],
                            dst: [str, Path],
                            compression: typing.Optional[str] = None,
                            override: bool = False) -> None:
    """ Removes all unlabeled events from a dataset labeled by DCTag

    After annotating datasets wtih DCTag, some of the events were skipped and
    therefore do not have an `ml_score` assigned to them.
    This function removes these skipped events and stores the reduced dataset
    in `dst`.

    Parameter
    ---------
    src: [str, pathlib.Path]
        Path of the dataset that should be cleaned
    dest: [str, pathlib.Path]
        Path where the cleaned (and thus reduced) dataset should be saved
    """
    src = Path(src)
    dst = Path(dst)

    compression_kwargs = {"compression": compression}

    dst.parent.mkdir(parents=True, exist_ok=True)

    with dclab.new_dataset(src) as ds:
        # If there are no labelled events in the dataset and no `ml_class`
        # then the filtering below will not work and not remove any events in
        # the dataset. Therefore we need to check here if `ml_class` exists
        # and after filtering check, if some events still remained.
        # Edge case 1:
        #     Dataset was not labelled -> no `ml_class`-feature
        #     -> no events removed. Thus we need the Exception below

        if "ml_class" not in ds.features:
            raise DatasetNotLabeledException
        # Filter out the events that have no dctag label assigned during
        # annotation. Here we take a very large arbitrary number as max value
        ds.config["filtering"]["ml_class min"] = 0
        ds.config["filtering"]["ml_class max"] = 1000
        ds.apply_filter()

        # Edge case 2:

        #     Dataset was run through DCTag, but no cell was labelled,
        #     or potentially labelled, but then reset. This will cause the
        #     `ml_class` to exist, but only contain '-1' entries.
        #     This dataset then should not be exported!
        if np.sum(ds.filter.all) == 0:
            warning_text = (f"Dataset at {src=} does not contain any labelled "
                            f"events. No dataset will be output.")
            warnings.warn(warning_text, EmptyLabeledDatasetNotExported)
            logger.info(warning_text)
        else:
            features = ds.features_innate
            ds.export.hdf5(path=dst, features=features,
                           filtered=True,
                           compression_kwargs=compression_kwargs,
                           override=override)


def fill_all_annotation_features(src: [str, Path]) -> None:
    """Adds all remaining ml_score-features to the RT-DC dataset inplace

    Labelling with DCTag only adds those `ml_score` to the RTDC-dataset that
    have been used in the labelling step. This function adds the remaining
    `ml_score` features to the dataset containing only zeros. This is
    currently needed for the training.
    The list of all `ml_score_...`-features can be found in file
    `dcml.definitions.ml_score_to_int.json`.

    Parameter
    ---------
    src: [str, Path]
        Path to the RT-DC file which needs to be filled up with the remaining
        `ml_score_...` features.
    Note
    ----
    This happens **inplace**!
    """
    ml_score_to_int_dict = load_ml_score_to_int()
    with h5py.File(src, "r+") as hf:
        # delete previously computed feature "ml_class"
        # The `ml_class` features in normally an ancillary feature and will not
        # be written to the file when opened.
        # We still need to check if it exists, because one can export the
        # rtdc-file and if `ml_class` is defined in the list of features
        # it will also be written to the new RTDC-file. Writing to that file
        # another `ml_class` might lead to issues (e.g. concatenating
        # instead of replacing the already existing `ml_class`-array)
        try:
            del hf["events"]["ml_class"]
        except Exception as e:
            logger.info(
                f"Exception when deleting `ml_class` for dataset in "
                f"Path: {src}. It might not be an existing feature. "
                f"The remaining ml_score-features will be added anyways! "
                f"Thrown Error:\n{e}")
        arbitrary_feat_name = list(hf["events"].keys())[0]
        dataset_len = len(hf["events"][arbitrary_feat_name])
        emtpy_feat_array = np.zeros(dataset_len)
        for score_name in ml_score_to_int_dict.keys():
            if score_name not in hf["events"].keys():
                hf["events"].create_dataset(score_name,
                                            data=emtpy_feat_array)


