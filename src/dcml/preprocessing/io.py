def get_predictions(ds_path: Path,
                    model: OneModel,
                    batch_size: int,
                    num_workers: int,
                    device: str,
                    mean:float =None,
                    std:float = None,
                    brightness_factor:float | None = None
                    ) -> np.ndarray:
    """
    Get predictions from a trained model on a dataset.

    Parameters
    ----------
    ds_path: Path
        The path to the RTDC-dataset.
    model: BaseModel
        The trained model for making predictions.
    batch_size: int
        The batch size to use when processing the dataset.
    num_workers: int
        The number of parallel workers for data loading.
    device: str
        The device on which to perform model inference (e.g., 'cuda', 'cpu').
    mean: mean of the dataset to be used for normalization. If None the mean saved within
                      the model, which was used for training will be used
    std: standard deviation of the dataset to be used for normalization. If None the standard deviation saved within
                      the model, which was used for training will be used

    brightness_factor: if not None, it will be used to correct brightenss of the images by multiplying it with the images

    Returns
    -------
    np.ndarray
        An array containing the predictions generated by the model.

    Example
    -------
    >>> predictions = get_predictions(
    ...     ds_path='/path/to/dataset',
    ...     model=my_trained_model,
    ...     batch_size=64,
    ...     num_workers=4,
    ...     device='cuda'
    ... )
    """

    dataset_params = model.params["create_dataset"]
    class_label_dict = model.params["create_trainer"]["class_label_dict"]

    if mean is None:
        mean = dataset_params['mean']

    if std is None:
        std = dataset_params['std']

    # if p99 is None:
    #     p99 = dataset_params['p99']

    # if compute_mean_std:  # compute statistics from the dataset
    #     mean = None
    #     std = None
    # else:  # use the same statistics as was used for training
    #     mean = dataset_params['mean']
    #     std = dataset_params['std']

    MTL_mode = bool(getattr(model.model, 'num_heads', False)) == True

    dataset = create_single_dataset(hdf5_path=ds_path,
                                    required_data={"image": "image"},
                                    correct_background=False,
                                    crop_size=dataset_params["crop_size"],
                                    mean=mean,
                                    std=std,
                                    MTL=MTL_mode,
                                    brightness_factor=brightness_factor
                                    )

    dataloader = DataLoader(dataset,
                            batch_size=batch_size,
                            shuffle=False,
                            num_workers=num_workers)

    # Apply model
    # logger.info(f"Predicting Cells -- Start Time: {time.ctime()}")

    _, prediction_probs, _, _ = predict(model.model, dataloader, criterion=None, device=device, class_label_dict=class_label_dict)
    prediction_probs = np.array(prediction_probs, dtype=np.float64)

    return prediction_probs

